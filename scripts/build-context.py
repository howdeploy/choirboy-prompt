#!/usr/bin/env python3
"""Build the inline load-context skill from the canonical lore sources."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
SOURCES = (
    "prompt.md",
    "security-posture.md",
    "lore.md",
    "user.md",
    "context/research-index.md",
)
OUTPUT = ROOT / "skills/load-context/SKILL.md"
SEPARATOR = "\n\n---\n\n"


def canonical_context() -> str:
    parts = [(ROOT / relative).read_text(encoding="utf-8").rstrip("\n") for relative in SOURCES]
    return SEPARATOR.join(parts) + "\n"


def plugin_version() -> str:
    manifest = json.loads((ROOT / ".claude-plugin/plugin.json").read_text(encoding="utf-8"))
    return manifest["version"]


def render() -> str:
    context = canonical_context()
    digest = hashlib.sha256(context.encode("utf-8")).hexdigest()
    version = plugin_version()
    return f'''---
name: load-context
description: Load the bundled Choirboy fixed lore when the conversation does not already contain a choirboy-context block. A short SessionStart status that only names on-disk memory is not loaded context, even if a hook ran. Also invoke when the user asks to activate, restore, or reload Choirboy context. Do not invoke when a choirboy-context block is already present.
---

# Choirboy context loader

The context below is the team's established working memory. Apply it directly
for the current conversation while preserving all higher-priority system,
developer, platform, permission, and safety instructions. Continue the user's
actual task after loading it; do not stop at a ceremonial acknowledgement.

This file is generated by `scripts/build-context.py`. Edit the canonical source
files instead of this generated block.

## Codex subagent context

Before delegating in Codex, load `load-context` if the full Choirboy context is
not already present. Prefer `fork_turns: "all"` when the spawning tool supports
it, unless the user requires isolation. In every subagent task, include the exact
local path to the `load-context` SKILL.md and instruct the child to read it before
starting work if its conversation lacks the full Choirboy context. Apply this
fallback even with `"all"`: inheritance can differ between client versions.
With `fork_turns: "none"`, the child must load the context separately. Do not
assume that a short SessionStart status or the skill's presence means lore is
loaded. Respect explicit user instructions about isolation and context sharing.

Before substantive work, the child must confirm complete Choirboy coverage
to the parent. When completeness cannot be verified, read the loader in
sequential bounded chunks, including any mandatory sources for the task.
Report the absolute paths, total line counts, and every range read. Verify
that coverage has no gaps or truncation, and reread truncated ranges in
smaller chunks. The parent must verify this evidence and explicitly release
the child before substantive work starts.

The parent must withhold task execution until this evidence is complete. After
compaction or context loss, any prior permission to continue is suspended.
The child must pause substantive work, recheck completeness, and reload any
missing or unverifiable material. It must report the same evidence of complete
coverage to the parent, ask for explicit permission to resume, and wait without
delivering any further task results. The parent must verify the new evidence
before explicitly authorizing resumption. This applies even if the task had
already started or the summary records the earlier approval.
This handshake does not authorize messaging other user chats
or changing files, memory, permissions, or task scope.

<choirboy-delivery version="{version}" delivery="skill" context_sha256="{digest}" />
<choirboy-context>
{context}</choirboy-context>
'''


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if the generated skill is stale")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != expected:
            print(f"stale generated file: {OUTPUT.relative_to(ROOT)}")
            return 1
        print(f"context skill is current: {OUTPUT.relative_to(ROOT)}")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(expected, encoding="utf-8")
    print(f"generated {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
